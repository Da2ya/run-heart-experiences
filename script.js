function changeLanguage(lang) {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });
}

// --- SISTEMA DE RESEÑAS DINÁMICAS (LOCALSTORAGE) ---
const reviewForm = document.getElementById('reviewForm');
const reviewsContainer = document.getElementById('reviewsContainer');

document.addEventListener('DOMContentLoaded', () => {
    loadStoredReviews();
});

reviewForm.addEventListener('submit', function(e) {
    e.preventDefault();
    
    const name = document.getElementById('reviewerName').value.trim();
    const text = document.getElementById('reviewerText').value.trim();
    const ratingVal = document.querySelector('input[name="rating"]:checked').value;
    
    let starsString = '★'.repeat(ratingVal) + '☆'.repeat(5 - ratingVal);

    const newReview = {
        name: name,
        text: text,
        stars: starsString
    };

    saveReviewToStorage(newReview);
    appendReviewCard(newReview);

    reviewForm.reset();
    alert('¡Gracias por tu calificación! Tu comentario ya ha sido publicado con éxito.');
});

function appendReviewCard(review) {
    const card = document.createElement('div');
    card.classList.add('review-card');
    card.innerHTML = `
        <div class="review-stars">${review.stars}</div>
        <p class="review-text">"${review.text}"</p>
        <span class="review-author">- ${review.name}</span>
    `;
    reviewsContainer.prepend(card);
}

function saveReviewToStorage(review) {
    let reviews = JSON.parse(localStorage.getItem('runHeartReviews')) || [];
    reviews.push(review);
    localStorage.setItem('runHeartReviews', JSON.stringify(reviews));
}

function loadStoredReviews() {
    let reviews = JSON.parse(localStorage.getItem('runHeartReviews')) || [];
    reviews.forEach(review => {
        appendReviewCard(review);
    });
}